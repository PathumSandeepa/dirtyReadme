export function fillRectRgba(
  buffer: Uint8ClampedArray,
  bufW: number,
  bufH: number,
  x: number,
  y: number,
  w: number,
  h: number,
  rgba: readonly [number, number, number, number]
): void {
  const x0 = Math.max(0, Math.floor(x));
  const y0 = Math.max(0, Math.floor(y));
  const x1 = Math.min(bufW, Math.ceil(x + w));
  const y1 = Math.min(bufH, Math.ceil(y + h));
  const [r, g, b, a] = rgba;
  const alpha = a / 255;

  for (let py = y0; py < y1; py++) {
    for (let px = x0; px < x1; px++) {
      const idx = (py * bufW + px) * 4;
      if (alpha >= 1 || buffer[idx + 3] === 0) {
        buffer[idx] = r;
        buffer[idx + 1] = g;
        buffer[idx + 2] = b;
        buffer[idx + 3] = a;
      } else if (alpha > 0) {
        const inv = 1 - alpha;
        buffer[idx] = Math.round(r * alpha + buffer[idx] * inv);
        buffer[idx + 1] = Math.round(g * alpha + buffer[idx + 1] * inv);
        buffer[idx + 2] = Math.round(b * alpha + buffer[idx + 2] * inv);
        buffer[idx + 3] = Math.min(255, Math.round(a + buffer[idx + 3] * inv));
      }
    }
  }
}

export function drawPixelTextRgba(
  buffer: Uint8ClampedArray,
  bufW: number,
  bufH: number,
  text: string,
  originX: number,
  originY: number,
  scale = 1,
  rgba: readonly [number, number, number, number]
): void {
  const upper = text.toUpperCase();
  let cursorX = Math.round(originX);
  const startY = Math.round(originY);
  const pxSize = Math.max(1, Math.round(scale));

  for (let i = 0; i < upper.length; i++) {
    const ch = upper[i];
    const glyph = GLYPHS_5X7[ch] ?? GLYPHS_5X7[" "];
    for (let row = 0; row < glyph.length; row++) {
      const bits = glyph[row];
      for (let col = 0; col < bits.length; col++) {
        if (bits[col] === "1") {
          fillRectRgba(
            buffer,
            bufW,
            bufH,
            cursorX + col * pxSize,
            startY + row * pxSize,
            pxSize,
            pxSize,
            rgba
          );
        }
      }
    }
    cursorX += 6 * pxSize;
  }
}
